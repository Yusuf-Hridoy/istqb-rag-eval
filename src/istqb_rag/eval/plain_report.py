"""Write a run's results as plain English, for someone who will not read JSON.

`eval report` writes runs/<run-id>/report.md and `eval compare` writes
runs/<new>/comparison.md. Both read committed files only and make no API calls.
"""

import json
from pathlib import Path

from istqb_rag.eval.deterministic_metrics import citation_rate
from istqb_rag.eval.step2_judge_scores import METRIC_KEYS

# What each judge score actually means, in one line.
METRIC_MEANING = {
    "context_precision": (
        "Context precision",
        "how much of what was retrieved was actually relevant",
    ),
    "context_recall": (
        "Context recall",
        "how much of the reference answer the retrieved text covered",
    ),
    "faithfulness": (
        "Faithfulness",
        "how much of the answer is backed by the retrieved text",
    ),
    "response_relevancy": (
        "Response relevancy",
        "how directly the answer addresses the question",
    ),
}

WEAKEST_N = 5


def questions_by_id(golden_path: Path) -> dict[str, str]:
    """{id: question} from the golden dataset, which is committed."""
    out = {}
    if not golden_path.exists():
        return out
    for line in golden_path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            row = json.loads(line)
            out[row["id"]] = row["question"]
    return out


def _pct(value: float | None) -> str:
    return "not measured" if value is None else f"{value * 100:.0f}%"


def _scope_accuracy(rows: list[dict], row_type: str) -> tuple[float | None, int]:
    group = [r for r in rows if r["type"] == row_type]
    if not group:
        return (None, 0)
    ok = sum(1 for r in group if r["status"] in ("refused", "no_context"))
    return (ok / len(group), len(group))


def build_report(
    run_id: str, config: dict, summary: dict, rows: list[dict], questions: dict
) -> str:
    """The plain-English report for one run."""
    description = config.get("description") or "No description recorded for this run."
    lines = [
        f"# {run_id}",
        "",
        description,
        "",
        "## What this run was",
        "",
        f"- Answer model: `{config.get('answer_model', '?')}`",
        f"- Judge model: `{config.get('judge_model', '?')}`",
        # Runs made before these switches existed had only one behaviour each,
        # so an absent key means the original: page chunking, text answers,
        # prompt version 1.
        f"- Chunking: {config.get('chunking') or 'page'} · answer format: "
        f"{config.get('answer_format') or 'text'} · prompt version: "
        f"{config.get('prompt_version', 1)}",
        f"- Retrieved chunks per question (TOP_K): {config.get('top_k', '?')}",
        f"- Questions: {config.get('row_count', len(rows))}",
        "",
        "## Judge scores",
        "",
        "| Score | Result | What it means |",
        "|---|---|---|",
    ]
    for key in METRIC_KEYS:
        label, meaning = METRIC_MEANING[key]
        stats = summary.get("overall", {}).get(key, {})
        if stats.get("unmeasured") or stats.get("mean") is None:
            result = "not measured in this run"
        else:
            result = f"{stats['mean']:.2f} (over {stats['scored']} questions)"
        lines.append(f"| {label} | {result} | {meaning} |")

    answered = summary.get("in_scope_answer_rate", {})
    cite = citation_rate(rows)
    out_scope, out_n = _scope_accuracy(rows, "out_of_scope")
    not_in, not_in_n = _scope_accuracy(rows, "not_in_syllabus")

    lines += [
        "",
        "## Behaviour",
        "",
        f"- **Answered** {answered.get('answered', 0)} of "
        f"{answered.get('total', 0)} syllabus questions "
        f"({_pct(answered.get('rate'))}).",
        f"- **Cited a page** on {cite['cited']} of {cite['answered']} answers "
        f"({_pct(cite['rate'])}).",
        f"- **Declined correctly** on {_pct(out_scope)} of {out_n} off-topic questions "
        f"and {_pct(not_in)} of {not_in_n} testing questions the syllabus does not cover.",
    ]
    errors = summary.get("errors", {})
    if errors.get("count"):
        lines.append(f"- **Errors:** {errors['count']} question(s) failed to run.")

    worst = [w for w in summary.get("worst_10", []) if w.get("avg") is not None][:WEAKEST_N]
    if worst:
        lines += [
            "",
            f"## Weakest {len(worst)} questions",
            "",
            "| id | question | average score |",
            "|---|---|---|",
        ]
        for row in worst:
            question = questions.get(row["id"], "")
            lines.append(f"| `{row['id']}` | {question} | {row['avg']:.2f} |")

    lines += ["", "_Generated by `uv run python -m istqb_rag.eval report`._"]
    return "\n".join(lines) + "\n"


def build_comparison(base_id: str, new_id: str, data: dict, questions: dict) -> str:
    """The plain-English comparison of two runs."""
    lines = [
        f"# {new_id} compared with {base_id}",
        "",
        f"{data['rows_compared']} questions were in both runs, matched by id.",
        "",
        "## Judge scores",
        "",
        f"| Score | {base_id} | {new_id} | Change |",
        "|---|---|---|---|",
    ]
    for key in METRIC_KEYS:
        label, _ = METRIC_MEANING[key]
        m = data["metrics"][key]

        def cell(mean, n):
            return "not measured" if mean is None else f"{mean:.2f} (n={n})"

        change = "—" if m["delta"] is None else f"{m['delta']:+.2f}"
        lines.append(
            f"| {label} | {cell(m['base_mean'], m['base_n'])} "
            f"| {cell(m['new_mean'], m['new_n'])} | {change} |"
        )

    def rate(pair, key="rate"):
        value = pair[key] if isinstance(pair, dict) else pair[0]
        return "—" if value is None else f"{value * 100:.0f}%"

    lines += [
        "",
        "## Behaviour",
        "",
        f"| Measure | {base_id} | {new_id} |",
        "|---|---|---|",
        f"| Answered | {rate(data['answer_rate']['base'])} | {rate(data['answer_rate']['new'])} |",
        f"| Cited a page | {rate(data['citation_rate']['base'])} "
        f"| {rate(data['citation_rate']['new'])} |",
        f"| Declined off-topic correctly | {rate(data['out_of_scope_accuracy']['base'])} "
        f"| {rate(data['out_of_scope_accuracy']['new'])} |",
    ]

    changed = data.get("changed_rows", [])
    if not changed:
        lines += ["", "No question changed status or moved by more than 0.2."]
    else:
        lines += [
            "",
            f"## Questions that changed ({len(changed)})",
            "",
            "| id | question | what changed |",
            "|---|---|---|",
        ]
        for row in changed:
            bits = []
            if row["status_changed"]:
                bits.append(f"{row['base_status']} → {row['new_status']}")
            for key, move in row["moved"].items():
                label, _ = METRIC_MEANING[key]
                bits.append(f"{label.lower()} {move['base']} → {move['new']}")
            lines.append(f"| `{row['id']}` | {questions.get(row['id'], '')} | {'; '.join(bits)} |")

    lines += ["", "_Generated by `uv run python -m istqb_rag.eval compare`._"]
    return "\n".join(lines) + "\n"


def write_report(run_dir: Path, summary: dict, rows: list[dict], golden_path: Path) -> Path:
    config_path = run_dir / "config.json"
    config = json.loads(config_path.read_text(encoding="utf-8")) if config_path.exists() else {}
    body = build_report(run_dir.name, config, summary, rows, questions_by_id(golden_path))
    path = run_dir / "report.md"
    path.write_text(body, encoding="utf-8")
    return path


def write_comparison(run_dir: Path, base_id: str, data: dict, golden_path: Path) -> Path:
    body = build_comparison(base_id, run_dir.name, data, questions_by_id(golden_path))
    path = run_dir / "comparison.md"
    path.write_text(body, encoding="utf-8")
    return path
